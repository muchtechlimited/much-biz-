import { useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { ArrowLeft, Download, Printer } from 'lucide-react';
import { Button, Card, ErrorState, PageHeader, Spinner, TextField } from '../components/ui';
import { ApiError, downloadFile } from '../lib/api';
import { useToast } from '../lib/toast';
import { formatDate, formatMoney } from '../lib/format';
import { useFetch } from '../lib/useFetch';

interface Stmt {
  customer: { id: string; name: string; phone: string | null; email: string | null };
  business: { name: string; phone: string | null; email: string | null; address: string | null; currency: string };
  period: { from: string | null; to: string | null };
  opening_balance: number; closing_balance: number;
  totals: { sales: number; charged_to_account: number; refunds: number; payments: number };
  transactions: { date: string; type: string; reference: string; description: string; amount: number; debit: number; credit: number; balance: number }[];
  invoices: { number: string; issue_date: string; due_date: string; total: number; paid: number; outstanding: number }[];
  invoice_totals: { total: number; paid: number; outstanding: number };
}

/** Customer statement: filter by date range, print, or download a PDF generated by the server. */
export default function CustomerStatement() {
  const { id } = useParams();
  const { notify } = useToast();
  const [from, setFrom] = useState('');
  const [to, setTo] = useState('');
  const [busy, setBusy] = useState(false);
  const q = { date_from: from || undefined, date_to: to || undefined };
  const { data, loading, error, reload } = useFetch<Stmt>(id ? `/customers/${id}/statement` : null, q);
  const invalid = !!from && !!to && from > to;

  async function pdf() {
    setBusy(true);
    try { await downloadFile(`/customers/${id}/statement.pdf`, 'statement.pdf', q); }
    catch (e) { notify('error', e instanceof ApiError ? e.message : 'Could not download the PDF.'); }
    finally { setBusy(false); }
  }
  const m = (n: number) => formatMoney(n, data?.business.currency ?? 'NGN');

  return (
    <>
      <div className="no-print">
        <Link to="/customers" className="mb-2 inline-flex items-center gap-1 text-sm text-navy underline"><ArrowLeft className="h-4 w-4" /> Customers</Link>
        <PageHeader title="Customer statement" subtitle="Transactions, payments and balances for a period"
          actions={<><Button variant="secondary" onClick={() => window.print()} disabled={!data}><Printer className="h-4 w-4" /> Print</Button>
            <Button variant="gold" loading={busy} onClick={pdf} disabled={!data || invalid}><Download className="h-4 w-4" /> Download PDF</Button></>} />
        <Card className="mb-4">
          <div className="grid gap-3 sm:grid-cols-[1fr_1fr_auto] sm:items-end">
            <TextField label="From" type="date" value={from} onChange={(e) => setFrom(e.target.value)} />
            <TextField label="To" type="date" value={to} onChange={(e) => setTo(e.target.value)} error={invalid ? 'The start date is after the end date.' : undefined} />
            <Button variant="secondary" onClick={() => { setFrom(''); setTo(''); }}>All time</Button>
          </div>
        </Card>
      </div>
      {invalid ? null : loading && !data ? <Spinner /> : error || !data ? <ErrorState message={error ?? 'Statement unavailable.'} onRetry={reload} /> : (
        <Card className="print:border-0 print:shadow-none">
          <div className="flex flex-wrap justify-between gap-2">
            <div><p className="text-lg font-bold text-navy">{data.business.name}</p>
              <p className="text-sm text-grey-400">{[data.business.address, data.business.phone, data.business.email].filter(Boolean).join(' · ')}</p></div>
            <div className="text-right text-sm"><p className="font-semibold">Customer statement</p><p>{data.customer.name}</p>
              <p className="text-grey-400">{data.period.from ? formatDate(data.period.from) : 'Start'} – {data.period.to ? formatDate(data.period.to) : 'Today'}</p></div>
          </div>
          <dl className="mt-4 grid grid-cols-2 gap-3 text-sm sm:grid-cols-5">
            {([['Opening balance', data.opening_balance], ['Charged to account', data.totals.charged_to_account], ['Payments received', data.totals.payments],
              ['Refunds', data.totals.refunds], ['Closing balance', data.closing_balance]] as const).map(([l, v]) => (
              <div key={l} className="rounded-lg bg-grey-50 p-3"><dt className="text-xs text-grey-400">{l}</dt><dd className="money text-base font-bold text-navy">{m(v)}</dd></div>
            ))}
          </dl>
          <h2 className="mb-2 mt-6 text-base">Transactions</h2>
          {data.transactions.length === 0 ? <p className="text-sm text-grey-400">No transactions in this period.</p> : (
            <div className="overflow-x-auto">
              <table className="w-full min-w-[560px] text-left text-sm">
                <thead><tr className="border-b text-xs uppercase text-grey-400"><th className="py-1">Date</th><th>Description</th><th className="text-right">Debit</th><th className="text-right">Credit</th><th className="text-right">Balance</th></tr></thead>
                <tbody>
                  <tr className="border-b border-grey-100 italic"><td colSpan={4} className="py-1.5">Opening balance</td><td className="money text-right">{m(data.opening_balance)}</td></tr>
                  {data.transactions.map((t, i) => (
                    <tr key={i} className="border-b border-grey-100"><td className="py-1.5">{formatDate(t.date)}</td><td>{t.description}</td>
                      <td className="money text-right">{t.debit ? m(t.debit) : ''}</td><td className="money text-right">{t.credit ? m(t.credit) : ''}</td><td className="money text-right">{m(t.balance)}</td></tr>
                  ))}
                  <tr className="font-bold"><td colSpan={4} className="py-1.5">Closing balance (amount owed)</td><td className="money text-right">{m(data.closing_balance)}</td></tr>
                </tbody>
              </table>
            </div>
          )}
          {data.invoices.length > 0 && (<>
            <h2 className="mb-2 mt-6 text-base">Invoices issued in this period</h2>
            <div className="overflow-x-auto"><table className="w-full min-w-[520px] text-left text-sm">
              <thead><tr className="border-b text-xs uppercase text-grey-400"><th className="py-1">Invoice</th><th>Due</th><th className="text-right">Total</th><th className="text-right">Paid</th><th className="text-right">Outstanding</th></tr></thead>
              <tbody>{data.invoices.map((i) => <tr key={i.number} className="border-b border-grey-100"><td className="py-1.5">{i.number}</td><td>{formatDate(i.due_date)}</td><td className="money text-right">{m(i.total)}</td><td className="money text-right">{m(i.paid)}</td><td className="money text-right">{m(i.outstanding)}</td></tr>)}</tbody></table></div>
            <p className="mt-2 text-xs text-grey-400">Invoices are a separate receivable and are not included in the account balance above.</p>
          </>)}
        </Card>
      )}
    </>
  );
}
